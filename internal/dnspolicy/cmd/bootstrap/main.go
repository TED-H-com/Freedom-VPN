// Command bootstrap generates TEST ONLY admin credentials and initial
// AdGuardHome.yaml configurations for the local dev resolver stack in
// deploy/dev/adguard/.state/ (§12.2, §12.7).
package main

import (
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"golang.org/x/crypto/bcrypt"
)

// DevStateCredentials holds TEST ONLY credentials written to .state/credentials.json.
type DevStateCredentials struct {
	Comment  string `json:"_comment"`
	Username string `json:"username"`
	Password string `json:"password"`
}

func main() {
	stateDir := flag.String("state-dir", "", "Path to deploy/dev/adguard/.state directory")
	upstreamAddr := flag.String("upstream", "upstream:5353", "Upstream authoritative DNS server address")
	flag.Parse()

	if *stateDir == "" {
		fmt.Fprintln(os.Stderr, "error: --state-dir is required")
		os.Exit(1)
	}

	if err := run(*stateDir, *upstreamAddr); err != nil {
		fmt.Fprintf(os.Stderr, "bootstrap error: %v\n", err)
		os.Exit(1)
	}
}

func run(stateDir, upstreamAddr string) error {
	if err := os.MkdirAll(stateDir, 0o700); err != nil {
		return fmt.Errorf("mkdir %s: %w", stateDir, err)
	}

	credsPath := filepath.Join(stateDir, "credentials.json")
	envPath := filepath.Join(stateDir, "credentials.env")

	var creds DevStateCredentials
	if raw, err := os.ReadFile(credsPath); err == nil {
		_ = json.Unmarshal(raw, &creds)
	}

	if creds.Username == "" || creds.Password == "" {
		var randBytes [16]byte
		if _, err := rand.Read(randBytes[:]); err != nil {
			return fmt.Errorf("generate random password: %w", err)
		}
		// TEST ONLY - NOT A SECRET
		creds = DevStateCredentials{
			Comment:  "TEST ONLY - NOT A SECRET (auto-generated for local dev AdGuard Home resolvers)",
			Username: "admin",
			Password: "testonly-" + hex.EncodeToString(randBytes[:]),
		}
		credsJSON, err := json.MarshalIndent(creds, "", "  ")
		if err != nil {
			return err
		}
		if err := os.WriteFile(credsPath, append(credsJSON, '\n'), 0o600); err != nil {
			return fmt.Errorf("write %s: %w", credsPath, err)
		}
		envContent := fmt.Sprintf("# TEST ONLY - NOT A SECRET\nFVPN_DEV_ADGUARD_USER=%s\nFVPN_DEV_ADGUARD_PASS=%s\n", creds.Username, creds.Password)
		if err := os.WriteFile(envPath, []byte(envContent), 0o600); err != nil {
			return fmt.Errorf("write %s: %w", envPath, err)
		}
	}

	hashBytes, err := bcrypt.GenerateFromPassword([]byte(creds.Password), bcrypt.MinCost)
	if err != nil {
		return fmt.Errorf("bcrypt password: %w", err)
	}
	bcryptHash := string(hashBytes)

	for _, resolver := range []string{"resolver1", "resolver2"} {
		confDir := filepath.Join(stateDir, resolver, "conf")
		workDir := filepath.Join(stateDir, resolver, "work")
		if err := os.MkdirAll(confDir, 0o700); err != nil {
			return fmt.Errorf("mkdir %s: %w", confDir, err)
		}
		if err := os.MkdirAll(workDir, 0o700); err != nil {
			return fmt.Errorf("mkdir %s: %w", workDir, err)
		}
		confFile := filepath.Join(confDir, "AdGuardHome.yaml")
		cfgContent := renderAdGuardConfig(creds.Username, bcryptHash, upstreamAddr)
		if err := os.WriteFile(confFile, []byte(cfgContent), 0o600); err != nil {
			return fmt.Errorf("write %s: %w", confFile, err)
		}
	}

	return nil
}

