// controlgen generates aliases and partial-handler composition after oapi-codegen.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
)

func main() {
	out := flag.String("out", "internal/httpapi", "output directory")
	flag.Parse()
	fset := token.NewFileSet()
	models, err := parser.ParseFile(fset, "pkg/api/api.gen.go", nil, 0)
	must(err)
	var aliases bytes.Buffer
	fmt.Fprintln(&aliases, "// Code generated by controlgen. DO NOT EDIT.\npackage gen\nimport api \"github.com/TED-H-com/Freedom-VPN/pkg/api\"")
	for _, d := range models.Decls {
		if g, ok := d.(*ast.GenDecl); ok && g.Tok == token.TYPE {
			for _, s := range g.Specs {
				t := s.(*ast.TypeSpec)
				fmt.Fprintf(&aliases, "type %s = api.%s\n", t.Name, t.Name)
			}
		}
	}
	write(filepath.Join(*out, "gen/models.gen.go"), aliases.Bytes())
	server, err := parser.ParseFile(fset, filepath.Join(*out, "gen/server.gen.go"), nil, 0)
	must(err)
	var methods []string
	ast.Inspect(server, func(n ast.Node) bool {
		t, ok := n.(*ast.TypeSpec)
		if ok && t.Name.Name == "StrictServerInterface" {
			for _, f := range t.Type.(*ast.InterfaceType).Methods.List {
				methods = append(methods, f.Names[0].Name)
			}
		}
		return true
	})
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by controlgen. DO NOT EDIT.\npackage httpapi\nimport (\"context\";\"fmt\";\"github.com/TED-H-com/Freedom-VPN/internal/httpapi/gen\")\ntype Composite struct { sets []any }")
	fmt.Fprintln(&b, "// Compose rejects overlapping registrations at startup.\nfunc Compose(sets ...any) (*Composite,error) { if err:=validateHandlerSets(sets);err!=nil{return nil,err}; c:=&Composite{sets:append([]any(nil),sets...)}")
	for _, m := range methods {
		fmt.Fprintf(&b, "{ n:=0; for _,s:=range sets {if _,ok:=s.(interface{%s(context.Context,gen.%sRequestObject)(gen.%sResponseObject,error)});ok{n++}};if n>1{return nil,fmt.Errorf(\"duplicate handler: %s\")}}\n", m, m, m, m)
	}
	fmt.Fprintln(&b, "return c,nil }")
	for _, m := range methods {
		fmt.Fprintf(&b, "\nfunc(c *Composite)%s(ctx context.Context,r gen.%sRequestObject)(gen.%sResponseObject,error){for _,s:=range c.sets {if h,ok:=s.(interface{%s(context.Context,gen.%sRequestObject)(gen.%sResponseObject,error)});ok{return h.%s(ctx,r)}};return nil,errNotImplemented}\n", m, m, m, m, m, m, m)
	}
	fmt.Fprintln(&b, "var _ gen.StrictServerInterface = (*Composite)(nil)")
	write(filepath.Join(*out, "composition.gen.go"), b.Bytes())
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
func write(path string, b []byte) {
	v, err := format.Source(b)
	must(err)
	must(os.WriteFile(path, v, 0644))
}
