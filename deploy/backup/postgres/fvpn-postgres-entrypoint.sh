#!/usr/bin/env bash
# Wrapper entrypoint for the Freedom VPN PostgreSQL 17 + pgBackRest image (§15.4, §17.2).
# Prepares pgBackRest directories, renders /etc/postgresql/conf.d/50-fvpn-archiving.conf
# (honoring TEST ONLY lab overrides or isolated restore mode), and delegates to
# the upstream docker-entrypoint.sh.
set -euo pipefail

# Called by the restore helper immediately after pgBackRest succeeds, before
# any PostgreSQL process reads PGDATA. pgBackRest 2.60 appends its block last;
# an earlier lookalike marker in the primary is not provenance for this run.
rewrite_isolated_recovery() {
	local auto_conf="$1" rewritten
	if [[ ! -f "$auto_conf" ]]; then
		echo "isolated recovery: missing recovery block (postgresql.auto.conf absent)" >&2
		return 1
	fi
	rewritten="$(mktemp "${auto_conf}.fvpn.XXXXXX")"
	if ! LC_ALL=C awk -v quote="'" '
		/^# Recovery settings generated by pgBackRest restore on / {
			found = 1; count = 0; delete lines; next
		}
		found { lines[++count] = $0 }
		function fail(problem) {
			print "isolated recovery: " problem > "/dev/stderr"
			exit 1
		}
		END {
			if (!found) fail("missing recovery block")
			for (i = 1; i <= count; i++) {
				line = lines[i]
				if (line ~ /^[[:space:]]*(#|$)/) continue
				if (line ~ /^[[:space:]]*include(_if_exists|_dir)?([[:space:]]|=)/)
					fail("include directive in recovery block")
				if (line !~ ("^[a-z_]+ = " quote "[^" quote "\r]*" quote "$"))
					fail("malformed recovery setting")
				key = line; sub(/ .*/, "", key)
				if (key != "restore_command" && key != "recovery_target_time" &&
					key != "recovery_target_lsn" && key != "recovery_target_action" &&
					key != "recovery_target_inclusive")
					fail("unexpected recovery key: " key)
				if (seen[key]++) fail("duplicate recovery key: " key)
				output = output line "\n"
			}
			if (!seen["restore_command"]) fail("missing restore_command in recovery block")
			printf "%s", output
		}
	' "$auto_conf" >"$rewritten"; then
		rm -f "$rewritten"
		return 1
	fi
	chmod 0600 "$rewritten"
	chown --reference="$auto_conf" "$rewritten"
	mv -f "$rewritten" "$auto_conf"
}

# Sourceable for configuration tests; normal image startup continues below.
prepare_isolated_restore() {
	local config_dir="$1" data_dir="$2" db_user="$3" db_name="$4"
	local control parameter field value minimum
	for value in "$db_user" "$db_name"; do
		if [[ ! "$value" =~ ^[a-zA-Z_][a-zA-Z0-9_-]{0,62}$ ]]; then
			echo "fvpn-postgres-entrypoint: invalid isolated database/user name" >&2
			return 2
		fi
	done

	# This directory is in the disposable container, never the restored volume.
	# No includes: neither the primary configuration nor its HBA/ident is read.
	mkdir -p "$config_dir"
	printf '# Isolated verifier only; recovery settings supplied by the restore helper.\n' >"$config_dir/postgresql.conf"
	printf 'local "%s" "%s" peer map=fvpn_verifier\nhostnossl "%s" "%s" 127.0.0.1/32 trust\n' \
		"$db_name" "$db_user" "$db_name" "$db_user" >"$config_dir/pg_hba.conf"
	printf 'fvpn_verifier postgres "%s"\n' "$db_user" >"$config_dir/pg_ident.conf"

	# The runner has retained only this restore's generated recovery settings.
	# Pin the verifier boundary here too, including both recovery shell hooks.
	ISOLATED_ARGS=(
		-c "config_file=$config_dir/postgresql.conf"
		-c "hba_file=$config_dir/pg_hba.conf"
		-c "ident_file=$config_dir/pg_ident.conf"
		-c "data_directory=$data_dir"
		-c listen_addresses=127.0.0.1 -c port=5432
		-c unix_socket_directories=/var/run/postgresql
		-c ssl=off -c archive_mode=off -c archive_command= -c archive_library=
		-c archive_timeout=0 -c wal_level=replica -c hot_standby=on
		-c recovery_end_command= -c archive_cleanup_command=
		-c external_pid_file= -c logging_collector=off -c log_destination=stderr -c lc_messages=C
		# The restore runner must see the named DETAIL on a recovery resource
		# mismatch even if the primary suppressed warnings or their details.
		-c log_min_messages=warning -c log_error_verbosity=default
		# Host-specific libraries are unavailable in this verifier image. Do not
		# load inherited background workers or connection-time libraries.
		-c shared_preload_libraries= -c session_preload_libraries= -c local_preload_libraries=
	)
	control="$(LC_ALL=C pg_controldata "$data_dir")" || return
	for parameter in max_connections max_worker_processes max_wal_senders max_prepared_transactions max_locks_per_transaction; do
		field="$parameter"
		case "$parameter" in
		max_prepared_transactions) field=max_prepared_xacts ;;
		max_locks_per_transaction) field=max_locks_per_xact ;;
		esac
		value="$(awk -F: -v key="$field setting" '$1 == key {gsub(/[[:space:]]/, "", $2); print $2}' <<<"$control")"
		if [[ ! "$value" =~ ^(0|[1-9][0-9]{0,9})$ ]] || (( value > 2147483647 )); then
			echo "fvpn-postgres-entrypoint: cannot determine recovery parameter $parameter from pg_controldata" >&2
			return 1
		fi
		case "$parameter" in
		max_connections) minimum=100 ;;
		max_worker_processes) minimum=8 ;;
		max_wal_senders) minimum=10 ;;
		max_prepared_transactions) minimum=0 ;;
		max_locks_per_transaction) minimum=64 ;;
		esac
		(( value >= minimum )) || value="$minimum"
		ISOLATED_ARGS+=(-c "$parameter=$value")
	done
}

if [[ "${BASH_SOURCE[0]}" != "$0" ]]; then
	return 0
fi

STANZA="${FVPN_PGBACKREST_STANZA:-fvpn}"
if [[ ! "$STANZA" =~ ^[a-zA-Z0-9_-]+$ ]]; then
	echo "fvpn-postgres-entrypoint: invalid FVPN_PGBACKREST_STANZA" >&2
	exit 2
fi

ARCHIVE_TIMEOUT="${FVPN_PG_ARCHIVE_TIMEOUT:-300s}"
if [[ ! "$ARCHIVE_TIMEOUT" =~ ^[1-9][0-9]*(ms|s|min)$ ]]; then
	echo "fvpn-postgres-entrypoint: invalid FVPN_PG_ARCHIVE_TIMEOUT (expected e.g. 300s)" >&2
	exit 2
fi

ISOLATED_RESTORE="${FVPN_PG_ISOLATED_RESTORE:-0}"
PG_USER="${POSTGRES_USER:-postgres}"
PG_DB="${POSTGRES_DB:-$PG_USER}"
PGDATA_DIR="${PGDATA:-/var/lib/postgresql/data}"

if [[ "$(id -u)" == "0" ]]; then
	install -d -o postgres -g postgres -m 0750 \
		/var/log/pgbackrest \
		/var/spool/pgbackrest \
		/etc/pgbackrest \
		/etc/postgresql/conf.d
	# Only chown /var/lib/pgbackrest when not mounted read-only (isolated restores mount :ro).
	if [[ "$ISOLATED_RESTORE" != "1" ]] && [[ -w /var/lib/pgbackrest ]]; then
		chown -R postgres:postgres /var/lib/pgbackrest
		chmod 0750 /var/lib/pgbackrest
	fi
fi

ARCHIVING_CONF="/etc/postgresql/conf.d/50-fvpn-archiving.conf"
if [[ "$ISOLATED_RESTORE" != "1" ]] && [[ -w /etc/postgresql/conf.d ]]; then
	cat >"$ARCHIVING_CONF" <<EOF
# Freedom VPN PostgreSQL 17 WAL Archiving Configuration (§3.1, §15.4, §17.2)
wal_level = replica
archive_mode = on
archive_timeout = ${ARCHIVE_TIMEOUT}
archive_command = 'pgbackrest --stanza=${STANZA} archive-push %p'
max_wal_senders = 5
EOF
	if [[ "$(id -u)" == "0" ]]; then
		chown postgres:postgres "$ARCHIVING_CONF"
		chmod 0644 "$ARCHIVING_CONF"
	fi
fi

# Ensure existing PGDATA postgresql.conf includes /etc/postgresql/conf.d.
if [[ "$ISOLATED_RESTORE" != "1" ]] && [[ -f "${PGDATA_DIR}/postgresql.conf" ]] && [[ -w "${PGDATA_DIR}/postgresql.conf" ]]; then
	if ! grep -qF "/etc/postgresql/conf.d" "${PGDATA_DIR}/postgresql.conf"; then
		printf "\ninclude_dir = '/etc/postgresql/conf.d'\n" >>"${PGDATA_DIR}/postgresql.conf"
	fi
fi

# Render default local POSIX pgBackRest config unless caller mounted a custom config
# and set FVPN_PGBACKREST_CUSTOM_CONFIG=1.
PGBACKREST_CONF="/etc/pgbackrest/pgbackrest.conf"
if [[ "${FVPN_PGBACKREST_CUSTOM_CONFIG:-0}" != "1" ]] && [[ -w /etc/pgbackrest ]]; then
	PGBACKREST_REPO1_CIPHER_PASS="${PGBACKREST_REPO1_CIPHER_PASS:-${FVPN_PGBACKREST_CIPHER_PASS:-}}"
	if [[ -n "$PGBACKREST_REPO1_CIPHER_PASS" ]]; then
		export PGBACKREST_REPO1_CIPHER_PASS
		export PGBACKREST_REPO1_CIPHER_TYPE="${PGBACKREST_REPO1_CIPHER_TYPE:-aes-256-cbc}"
	else
		unset PGBACKREST_REPO1_CIPHER_PASS
	fi
	cat >"$PGBACKREST_CONF" <<EOF
# Freedom VPN pgBackRest container configuration (§17.2)
[global]
repo1-type=posix
repo1-cipher-type=${PGBACKREST_REPO1_CIPHER_TYPE:-none}
repo1-path=/var/lib/pgbackrest
repo1-retention-full-type=count
repo1-retention-full=7
repo1-retention-diff=7
process-max=2
log-level-console=warn
log-level-file=info
log-path=/var/log/pgbackrest
spool-path=/var/spool/pgbackrest
start-fast=y
archive-async=n
compress-type=zst

[${STANZA}]
pg1-path=${PGDATA_DIR}
pg1-port=5432
pg1-user=${PG_USER}
pg1-database=${PG_DB}
pg1-socket-path=/var/run/postgresql
EOF
	if [[ "$(id -u)" == "0" ]]; then
		chown postgres:postgres "$PGBACKREST_CONF"
		chmod 0640 "$PGBACKREST_CONF"
	fi
fi

if [[ "$ISOLATED_RESTORE" == "1" ]]; then
	prepare_isolated_restore /etc/postgresql/fvpn-isolated "$PGDATA_DIR" "$PG_USER" "$PG_DB"
	chown -R root:postgres /etc/postgresql/fvpn-isolated
	chmod 0750 /etc/postgresql/fvpn-isolated
	chmod 0640 /etc/postgresql/fvpn-isolated/*
	set -- "$@" "${ISOLATED_ARGS[@]}"
fi

exec /usr/local/bin/docker-entrypoint.sh "$@"
