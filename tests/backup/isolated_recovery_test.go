// The format is captured from the pinned pgBackRest image by the AT30 drill.
const recoveryMarker = "# Recovery settings generated by pgBackRest restore on "

func TestAT30_IsolatedRecoveryRewrite(t *testing.T) {
	generated := "restore_command = 'pgbackrest archive-get %f \"%p\"'\nrecovery_target_lsn = '0/6000170'\nrecovery_target_inclusive = 'false'\nrecovery_target_action = 'promote'\n"
	for _, tc := range []struct{ name, input, problem string }{
		{"last_block", "# old comment\nzero_damaged_pages = 'on'\ninclude = 'host.conf'\n" + recoveryMarker + "2000-01-01 00:00:00\nrecovery_end_command = 'false'\ninclude_if_exists = 'host.conf'\n" + recoveryMarker + "2026-01-01 00:00:00\n" + generated, ""},
		{"missing_block", "restore_command = 'false'\n", "missing recovery block"},
		{"extra_key", recoveryMarker + "2026-01-01 00:00:00\n" + generated + "zero_damaged_pages = 'on'\n", "unexpected recovery key: zero_damaged_pages"},
		{"include", recoveryMarker + "2026-01-01 00:00:00\n" + generated + "include_if_exists = 'host.conf'\n", "include directive in recovery block"},
		{"malformed", recoveryMarker + "2026-01-01 00:00:00\nrestore_command = 'unterminated\n", "malformed recovery setting"},
		{"duplicate", recoveryMarker + "2026-01-01 00:00:00\n" + generated + "recovery_target_action = 'pause'\n", "duplicate recovery key: recovery_target_action"},
		{"no_restore_command", recoveryMarker + "2026-01-01 00:00:00\n", "missing restore_command in recovery block"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			file := filepath.Join(t.TempDir(), "postgresql.auto.conf")
			if err := os.WriteFile(file, []byte(tc.input), 0o600); err != nil {
				t.Fatal(err)
			}
			cmd := exec.Command("bash", "-c", `source ../../deploy/backup/postgres/fvpn-postgres-entrypoint.sh; rewrite_isolated_recovery "$1"`, "_", file)
			out, err := cmd.CombinedOutput()
			got, readErr := os.ReadFile(file)
			if readErr != nil {
				t.Fatal(readErr)
			}
			if tc.problem != "" {
				if err == nil || !strings.Contains(string(out), tc.problem) {
					t.Fatalf("expected %q: %v %s", tc.problem, err, out)
				}
				if string(got) != tc.input {
					t.Fatal("failed rewrite modified the input")
				}
			} else if err != nil || string(got) != generated {
				t.Fatalf("only this restore's block must survive unchanged: %v %s\n%s", err, out, got)
			}
		})
	}
}

func TestAT30_IsolatedOwnershipAndForwarding(t *testing.T) {
	for _, scenario := range []string{"failure", "helper_failure", "preexisting", "refuse_server", "refuse_helper", "refuse_mounted", "raced_volume", "raced_helper", "success", "compatibility"} {
		t.Run(scenario, func(t *testing.T) {
			dir := t.TempDir()
			if scenario == "preexisting" {
				if err := os.WriteFile(filepath.Join(dir, "volume"), []byte("preserve me"), 0o600); err != nil {
					t.Fatal(err)
				}
			}
			stub := `#!/bin/bash
set -eu
printf '%s\0' "$@" >> "$STUB_DIR/argv"
printf '\n' >> "$STUB_DIR/argv"
owner=
for arg in "$@"; do
  case "$arg" in fvpn.backup.restore-owner=*) owner="${arg#*=}" ;; esac
done
case "$1" in
ps)
  case "$SCENARIO:$4" in
    refuse_server:name=\^/unit-pg\$|refuse_helper:name=\^/unit-pg-init\$|refuse_mounted:volume=unit-data) echo existing ;;
  esac ;;
volume)
  case "$2" in
    ls) if [[ -f "$STUB_DIR/volume" ]]; then echo unit-data; fi ;;
    create)
      touch "$STUB_DIR/volume"
      if [[ "$SCENARIO" == raced_volume ]]; then owner=another-invocation; fi
      printf '%s' "$owner" > "$STUB_DIR/volume-owner" ;;
    inspect) cat "$STUB_DIR/volume-owner" ;;
    rm) rm -f "$STUB_DIR/volume" ;;
  esac ;;
run)
  if [[ "$2" == --rm ]]; then
    touch "$STUB_DIR/helper"
    if [[ "$SCENARIO" == raced_helper ]]; then
      echo another-invocation > "$STUB_DIR/helper-owner"
      exit 125
    fi
    printf '%s' "$owner" > "$STUB_DIR/helper-owner"
    if [[ "$SCENARIO" == preexisting || "$SCENARIO" == helper_failure ]]; then exit 2; fi
    rm "$STUB_DIR/helper"
  else
    touch "$STUB_DIR/server"
    printf '%s' "$owner" > "$STUB_DIR/server-owner"
  fi ;;
inspect)
  case "$3" in
    *restore-owner*)
      case "${@: -1}" in
        unit-pg) printf 'unit-pg-id '; cat "$STUB_DIR/server-owner" ;;
        unit-pg-init) printf 'unit-pg-init-id '; cat "$STUB_DIR/helper-owner" ;;
      esac ;;
    *NetworkMode*) echo none ;;
    *NetworkSettings.Ports*) echo 0 ;;
    *State.Running*) if [[ "$SCENARIO" == failure ]]; then echo false; else echo true; fi ;;
  esac ;;
logs) echo 'TEST ONLY preparation failed' ;;
exec) echo promoted ;;
rm)
  for arg in "$@"; do
    case "$arg" in
      unit-pg|unit-pg-id) rm -f "$STUB_DIR/server" ;;
      unit-pg-init|unit-pg-init-id) rm -f "$STUB_DIR/helper" ;;
    esac
  done ;;
*) exit 99 ;;
esac
`
			if err := os.WriteFile(filepath.Join(dir, "docker"), []byte(stub), 0o700); err != nil {
				t.Fatal(err)
			}
			cmd := exec.Command("bash", "../../deploy/backup/restore-pitr.sh", "--latest", "--isolated-container", "unit-pg", "--target-volume", "unit-data", "--repo-volume", "unit-repo")
			// TEST ONLY - NOT A SECRET. Values must never appear on Docker argv.
			cmd.Env = append(os.Environ(), "PATH="+dir+":"+os.Getenv("PATH"), "STUB_DIR="+dir, "SCENARIO="+scenario,
				"PGBACKREST_REPO1_CIPHER_PASS=TEST_ONLY_CIPHER", "PGBACKREST_REPO1_CIPHER_TYPE=aes-256-cbc",
				"PGBACKREST_REPO1_S3_KEY_SECRET=TEST_ONLY_REMOTE", "PGBACKREST_REPO1_S3_BUCKET=example.invalid")
			if scenario == "compatibility" {
				cmd.Env = append(cmd.Env, "PGBACKREST_REPO1_CIPHER_PASS=", "FVPN_PGBACKREST_CIPHER_PASS=TEST_ONLY_CIPHER")
			}
			out, err := cmd.CombinedOutput()
			success := scenario == "success" || scenario == "compatibility"
			if (err == nil) != success {
				t.Fatalf("unexpected restore result: %v %s", err, out)
			}
			for _, object := range []string{"server", "helper", "volume"} {
				_, statErr := os.Stat(filepath.Join(dir, object))
				want := (success && object != "helper") || ((scenario == "preexisting" || scenario == "raced_volume") && object == "volume") || (scenario == "raced_helper" && object == "helper")
				if (statErr == nil) != want {
					t.Errorf("cleanup ownership: %s exists=%v want=%v", object, statErr == nil, want)
				}
			}
			if scenario == "preexisting" {
				contents, _ := os.ReadFile(filepath.Join(dir, "volume"))
				if string(contents) != "preserve me" {
					t.Error("cleanup removed or changed pre-existing volume contents")
				}
			}
			argv, err := os.ReadFile(filepath.Join(dir, "argv"))
			if err != nil {
				t.Fatal(err)
			}
			if strings.Contains(string(argv), "TEST_ONLY_") || strings.Contains(string(argv), "PGBACKREST_REPO1_S3_") {
				t.Error("Docker argv forwarded a remote option or a credential value")
			}
			if strings.HasPrefix(scenario, "refuse_") || success {
				if strings.Contains(string(argv), "\nrm\x00") || strings.Contains(string(argv), "volume\x00rm\x00") {
					t.Error("refusal/success must remove nothing")
				}
			}
			if success {
				for _, key := range []string{"PGBACKREST_REPO1_CIPHER_PASS", "PGBACKREST_REPO1_CIPHER_TYPE"} {
					if strings.Count(string(argv), "-e\x00"+key+"\x00") != 2 {
						t.Errorf("both Docker runs must forward only the cipher input %s by name", key)
					}
				}
			}
		})
	}
}
