export function buildOverviewSummary(
  nodes: readonly NodeItem[],
  members: readonly MemberItem[],
): AdminOverviewSummary {
  return {
    available_exits_count: nodes.filter((n) => n.serving_allowed).length,
    total_nodes_count: nodes.length,
    online_nodes_count: nodes.filter((n) => n.control_status === 'online').length,
    stale_nodes_count: nodes.filter((n) => n.control_status === 'stale').length,
    offline_nodes_count: nodes.filter((n) => n.control_status === 'offline').length,
    safety_failed_nodes_count: nodes.filter((n) => n.safety_status === 'failed').length,
    pending_or_failed_enrollments_count: nodes.filter(
      (n) => n.lifecycle_state === 'enrolling' || n.provisioning_state === 'failed',
    ).length,
    update_attention_nodes_count: nodes.filter(
      (n) =>
        n.update_state === 'failed' ||
        n.update_state === 'rolled_back' ||
        n.update_state === 'waiting_online',
    ).length,
    active_members_count: members.filter(
      (m) =>
        m.entitlement_state === 'active' ||
        m.entitlement_state === 'cancel_at_period_end' ||
        m.entitlement_state === 'grace',
    ).length,
    throttled_members_count: members.filter((m) => m.fup_tier_index > 0).length,
    suspended_or_expired_members_count: members.filter(
      (m) =>
        m.entitlement_state === 'suspended' ||
        m.entitlement_state === 'expired' ||
        m.entitlement_state === 'closed',
    ).length,
    as_of: '2026-10-29T11:45:00Z',
  };
}

