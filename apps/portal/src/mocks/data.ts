export function createMultiStepOperation(params: {
  operationId: string;
  kind: string;
  resourceVersion?: string;
  desiredGeneration?: string;
  observedGeneration?: string;
  finalStatus?: 'succeeded' | 'partially_succeeded';
  summaryCode?: string;
  stepNames?: string[];
}): { polls: Operation[] } {
  const stepNames = params.stepNames ?? [
    'agent_policy',
    'netbird_route_readback',
    'data_path_probe',
  ];
  const finalStatus = params.finalStatus ?? 'succeeded';

  const poll0: Operation = {
    operation_id: params.operationId,
    kind: params.kind,
    status: 'running',
    resource_version: params.resourceVersion ?? '43',
    desired_generation: params.desiredGeneration ?? '129',
    observed_generation: params.observedGeneration ?? '128',
    steps: stepNames.map((name, idx) => ({
      name,
      status: idx === 0 ? 'succeeded' : idx === 1 ? 'running' : 'pending',
    })),
    created_at: '2026-10-29T11:45:00Z',
  };

  const poll1: Operation = {
    ...poll0,
    status: finalStatus,
    observed_generation:
      finalStatus === 'succeeded'
        ? (params.desiredGeneration ?? '129')
        : (params.observedGeneration ?? '128'),
    summary_code: params.summaryCode,
    steps: stepNames.map((name, idx) => ({
      name,
      status:
        finalStatus === 'partially_succeeded' && idx === stepNames.length - 1
          ? 'pending'
          : 'succeeded',
      detail:
        finalStatus === 'partially_succeeded' && idx === stepNames.length - 1
          ? 'Node offline; bounded by lease expiry'
          : undefined,
    })),
    completed_at: '2026-10-29T11:45:05Z',
  };

  return { polls: [poll0, poll1] };
}
